<?php
require_once("../app/config/database.php");
$conn = conn(); require_student();
require_once("../vendor/tcpdf/fpdf.php");

$student_id = (int)$_SESSION["student_id"];
$st = mysqli_fetch_assoc(mysqli_query($conn, "SELECT * FROM students WHERE id=$student_id"));

$results = mysqli_query($conn, "SELECT r.*, e.exam_title, e.exam_mode, e.total_marks AS exam_total, s.subject_name FROM results r LEFT JOIN exams e ON r.exam_id=e.id LEFT JOIN subjects s ON e.subject_id=s.id WHERE r.student_id=$student_id ORDER BY r.id ASC");
$all = [];
while ($r = mysqli_fetch_assoc($results)) $all[] = $r;

$total = count($all); $pass=0; $fail=0; $sumPct=0; $bestPct=0; $bestExam=''; $lastTheta=null; $lastSkill=''; $aiInsight='';
foreach ($all as $r) {
    $p = round((float)$r['percentage'],1); $sumPct += $p;
    if ($r['status']=='Pass') $pass++; else $fail++;
    if ($p > $bestPct) { $bestPct = $p; $bestExam = $r['exam_title']; }
    if ($r['theta_score'] !== null) $lastTheta = round((float)$r['theta_score'],2);
    if (!empty($r['skill_category'])) $lastSkill = $r['skill_category'];
}
$avgPct = $total > 0 ? round($sumPct / $total, 1) : 0;
$aiInsight = !empty($all[0]['ai_insight']) ? $all[0]['ai_insight'] : '';

$pdf = new FPDF();
$pdf->AliasNbPages();
$pdf->SetAutoPageBreak(true, 25);

// ─── Cover Page ───
$pdf->AddPage();
$pdf->Ln(30);
$pdf->SetFont('Helvetica','B',22);
$pdf->Cell(0,12,'AI-Based Adaptive Online',0,1,'C');
$pdf->Cell(0,12,'Examination',0,1,'C');
$pdf->Ln(6);
$pdf->SetFont('Helvetica','',12);
$pdf->Cell(0,8,'Student Performance Report',0,1,'C');
$pdf->Ln(10);

$pdf->SetDrawColor(79,70,229);
$pdf->SetLineWidth(0.5);
$pdf->Line(60, $pdf->GetY(), 150, $pdf->GetY());
$pdf->Ln(12);

$pdf->SetFont('Helvetica','',11);
$pdf->Cell(50,8,'Student Name:',0,0);
$pdf->SetFont('Helvetica','B',11);
$pdf->Cell(0,8,h($st['name']),0,1);
$pdf->SetFont('Helvetica','',11);
$pdf->Cell(50,8,'Email:',0,0);
$pdf->Cell(0,8,h($st['email']),0,1);
$pdf->Cell(50,8,'Course:',0,0);
$pdf->Cell(0,8,h($st['course']).' - Sem '.h($st['semester']),0,1);
$pdf->Cell(50,8,'Phone:',0,0);
$pdf->Cell(0,8,h($st['phone']),0,1);
$pdf->Ln(6);

// Stats
$pdf->SetFont('Helvetica','B',10);
$pdf->Cell(30,6,"Total Exams: $total",0,0);
$pdf->Cell(25,6,"Pass: $pass",0,0);
$pdf->Cell(25,6,"Fail: $fail",0,0);
$pdf->Cell(30,6,"Average: $avgPct%",0,0);
$pdf->Cell(30,6,"Best: $bestPct%",0,1);
if ($lastTheta !== null) $pdf->Cell(30,6,"Theta: $lastTheta",0,0);
if ($lastSkill) $pdf->Cell(30,6,"Skill: $lastSkill",0,1);
$pdf->Ln(4);

$pdf->SetFont('Helvetica','',9);
$pdf->Cell(0,6,"Report Generated: ".date('d M Y h:i A'),0,1,'R');
$pdf->Ln(10);

// ─── Attempt History ───
$pdf->AddPage();
$pdf->SetFont('Helvetica','B',16);
$pdf->Cell(0,10,'Exam History',0,1,'L');
$pdf->Ln(4);

foreach ($all as $idx => $r) {
    $pct = round((float)$r['percentage'],1);
    $mt = max((int)$r['exam_total'], (int)$r['total_questions'], 1);

    $pdf->SetFillColor(245,247,250);
    $pdf->Rect(10,$pdf->GetY(),190,24,'F');
    $pdf->SetFont('Helvetica','B',10);
    $pdf->Cell(0,6,'Attempt #'.($idx+1).' - '.h($r['exam_title']),0,1);
    $pdf->SetFont('Helvetica','',9);
    $pdf->Cell(45,5,'Subject: '.h($r['subject_name']),0,0);
    $pdf->Cell(35,5,"Marks: ".(int)$r['marks_obtained']."/$mt",0,0);
    $pdf->Cell(25,5,"Score: $pct%",0,0);
    $pdf->SetFont('Helvetica','B',9);
    $pdf->Cell(20,5,$r['status'],0,1);
    $pdf->SetFont('Helvetica','',8);
    $pdf->Cell(0,5,h($r['submitted_at'] ?? ''),0,1);
    $pdf->Ln(3);
}

// ─── AI Analysis ───
if ($aiInsight) {
    $pdf->AddPage();
    $pdf->SetFont('Helvetica','B',16);
    $pdf->Cell(0,10,'AI Performance Analysis',0,1,'L');
    $pdf->Ln(4);
    $pdf->SetFont('Helvetica','',10);
    $pdf->MultiCell(0,6,h($aiInsight));
}

// ─── Footer ───
$pdf->SetY(-20);
$pdf->SetFont('Helvetica','',8);
$pdf->Cell(0,10,'Generated by AI-Based Adaptive Online Examination System | Page '.$pdf->PageNo().'/{nb}',0,0,'C');

$pdf->Output('D', 'My_Report_'.$st['name'].'.pdf');
